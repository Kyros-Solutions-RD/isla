//  Clipboard history that stays on your Mac. Anything marked as concealed or
//  transient by password managers is never recorded.
//

import AppKit
import SwiftUI

enum ClipKind: String, Codable, CaseIterable, Identifiable {
    case text, link, image, file, color

    var id: String { rawValue }

    var title: LocalizedStringKey {
        switch self {
        case .text: "Text"
        case .link: "Links"
        case .image: "Images"
        case .file: "Files"
        case .color: "Colors"
        }
    }

    var symbol: String {
        switch self {
        case .text: "text.alignleft"
        case .link: "link"
        case .image: "photo"
        case .file: "doc"
        case .color: "paintpalette"
        }
    }
}

struct ClipItem: Identifiable, Codable, Hashable {
    let id: UUID
    var kind: ClipKind
    var text: String?
    var fileURLs: [URL]?
    var imageFile: String?
    var sourceBundleID: String?
    var date: Date
    var isPinned: Bool

    var preview: String {
        switch kind {
        case .text, .link, .color: return text ?? ""
        case .file: return fileURLs?.map(\.lastPathComponent).joined(separator: ", ") ?? ""
        case .image: return String(localized: "Image")
        }
    }
}

@Observable
@MainActor
final class ClipboardStore {
    static let shared = ClipboardStore()

    static let defaultIgnoredApps = [
        "com.apple.keychainaccess", "com.apple.Passwords", "com.1password.1password", "com.agilebits.onepassword7",
        "com.bitwarden.desktop", "com.lastpass.LastPass", "com.dashlane.dashlanephonefinal", "org.keepassxc.keepassxc",
    ]

    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping",
        "Pasteboard generator type", "com.apple.is-remote-clipboard",
    ]

    private(set) var items: [ClipItem] = []
    private(set) var images: [UUID: NSImage] = [:]
    private(set) var isPaused = false

    @ObservationIgnored private var changeCount = NSPasteboard.general.changeCount
    @ObservationIgnored private var timer: Timer?
    @ObservationIgnored private let fileName = "clipboard.json"
    @ObservationIgnored private let imageFolder = Storage.folder("Clipboard")

    private init() {
        items = Storage.load([ClipItem].self, from: fileName) ?? []
    }

    func start() {
        timer?.invalidate()
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { _ in
            MainActor.assumeIsolated { ClipboardStore.shared.poll() }
        }
        timer?.tolerance = 0.2
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    func togglePause() { isPaused.toggle() }

    // MARK: Capture

    private func poll() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != changeCount else { return }
        changeCount = pasteboard.changeCount
        guard Preferences.shared.clipboardEnabled, !isPaused else { return }

        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.ignoredTypes) else { return }
        let source = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        if let source, Preferences.shared.clipboardIgnoredApps.contains(source) { return }
        guard let item = makeItem(from: pasteboard, source: source) else { return }
        insert(item)
    }

    private func makeItem(from pasteboard: NSPasteboard, source: String?) -> ClipItem? {
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            return ClipItem(id: UUID(), kind: .file, fileURLs: urls, sourceBundleID: source, date: .now, isPinned: false)
        }
        if let string = pasteboard.string(forType: .string)?.trimmingCharacters(in: .whitespacesAndNewlines), !string.isEmpty {
            let kind: ClipKind
            if let url = URL(string: string), let scheme = url.scheme, ["http", "https"].contains(scheme), !string.contains(" ") {
                kind = .link
            } else if string.range(of: #"^#?([0-9a-fA-F]{6}|[0-9a-fA-F]{3})$"#, options: .regularExpression) != nil {
                kind = .color
            } else {
                kind = .text
            }
            return ClipItem(id: UUID(), kind: kind, text: String(string.prefix(20_000)), sourceBundleID: source, date: .now, isPinned: false)
        }
        if let image = NSImage(pasteboard: pasteboard), let tiff = image.tiffRepresentation,
           let rep = NSBitmapImageRep(data: tiff), let png = rep.representation(using: .png, properties: [:]) {
            let id = UUID()
            let name = "\(id.uuidString).png"
            try? png.write(to: imageFolder.appendingPathComponent(name))
            images[id] = image
            return ClipItem(id: id, kind: .image, imageFile: name, sourceBundleID: source, date: .now, isPinned: false)
        }
        return nil
    }

    private func insert(_ item: ClipItem) {
        // Re-copying the same content moves it to the top instead of duplicating.
        if let existing = items.firstIndex(where: { $0.kind == item.kind && $0.text == item.text && $0.fileURLs == item.fileURLs && item.kind != .image }) {
            var moved = items.remove(at: existing)
            moved.date = .now
            items.insert(moved, at: 0)
        } else {
            items.insert(item, at: 0)
        }
        trim()
        persist()
    }

    private func trim() {
        let limit = max(10, Preferences.shared.clipboardLimit)
        var unpinned = 0
        var kept: [ClipItem] = []
        for item in items {
            if item.isPinned {
                kept.append(item)
            } else if unpinned < limit {
                kept.append(item)
                unpinned += 1
            } else if let file = item.imageFile {
                try? FileManager.default.removeItem(at: imageFolder.appendingPathComponent(file))
            }
        }
        items = kept
    }

    #if DEBUG
    func applyDemo() {
        let now = Date.now
        items = [
            ClipItem(id: UUID(), kind: .text, text: "La revisión de diseño se movió a las 3:00 p. m. en la sala Zona Colonial.", sourceBundleID: "com.apple.MobileSMS", date: now.addingTimeInterval(-40), isPinned: false),
            ClipItem(id: UUID(), kind: .link, text: "https://github.com/Kyros-Solutions-RD/isla", sourceBundleID: "com.apple.Safari", date: now.addingTimeInterval(-300), isPinned: true),
            ClipItem(id: UUID(), kind: .color, text: "#FF6B4A", sourceBundleID: "com.apple.Preview", date: now.addingTimeInterval(-900), isPinned: false),
            ClipItem(id: UUID(), kind: .text, text: "brew install --cask isla", sourceBundleID: "com.apple.Terminal", date: now.addingTimeInterval(-1800), isPinned: false),
            ClipItem(id: UUID(), kind: .text, text: "Gracias por la propuesta. Nos vemos el jueves para cerrar los detalles del lanzamiento.", sourceBundleID: "com.apple.mail", date: now.addingTimeInterval(-3600), isPinned: false),
        ]
    }
    #endif

    // MARK: Actions

    func image(for item: ClipItem) -> NSImage? {
        if let cached = images[item.id] { return cached }
        guard let file = item.imageFile, let image = NSImage(contentsOf: imageFolder.appendingPathComponent(file)) else { return nil }
        images[item.id] = image
        return image
    }

    /// Puts an item back on the system clipboard.
    func copy(_ item: ClipItem) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        switch item.kind {
        case .text, .link, .color:
            pasteboard.setString(item.text ?? "", forType: .string)
        case .file:
            pasteboard.writeObjects((item.fileURLs ?? []) as [NSURL])
        case .image:
            if let image = image(for: item) { pasteboard.writeObjects([image]) }
        }
        changeCount = pasteboard.changeCount
        if let index = items.firstIndex(of: item), !item.isPinned {
            var moved = items.remove(at: index)
            moved.date = .now
            items.insert(moved, at: 0)
            persist()
        }
        Haptics.tap()
    }

    /// Copies and, when allowed, pastes into the app the user was working in.
    func paste(_ item: ClipItem, closing controller: NotchWindowController?) {
        copy(item)
        controller?.close()
        guard Preferences.shared.clipboardAutoPaste, AXIsProcessTrusted() else {
            LiveActivityCenter.shared.post(.message(symbol: "doc.on.clipboard.fill", title: String(localized: "Copied")), duration: 1.3)
            return
        }
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.18) {
            let source = CGEventSource(stateID: .combinedSessionState)
            let down = CGEvent(keyboardEventSource: source, virtualKey: 9, keyDown: true)
            let up = CGEvent(keyboardEventSource: source, virtualKey: 9, keyDown: false)
            down?.flags = .maskCommand
            up?.flags = .maskCommand
            down?.post(tap: .cghidEventTap)
            up?.post(tap: .cghidEventTap)
        }
    }

    func togglePin(_ item: ClipItem) {
        guard let index = items.firstIndex(of: item) else { return }
        items[index].isPinned.toggle()
        persist()
    }

    func delete(_ item: ClipItem) {
        items.removeAll { $0.id == item.id }
        if let file = item.imageFile { try? FileManager.default.removeItem(at: imageFolder.appendingPathComponent(file)) }
        images[item.id] = nil
        persist()
    }

    func clearHistory(keepPinned: Bool = true) {
        let removed = items.filter { !keepPinned || !$0.isPinned }
        removed.compactMap(\.imageFile).forEach { try? FileManager.default.removeItem(at: imageFolder.appendingPathComponent($0)) }
        items.removeAll { !keepPinned || !$0.isPinned }
        persist()
    }

    private func persist() {
        Storage.save(items, to: fileName)
    }
}
